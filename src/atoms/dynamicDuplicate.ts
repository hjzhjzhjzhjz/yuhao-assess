/**
 * 動態重碼原子狀態
 * 存儲動態重碼分析的統計結果（可導出到 JSON）
 */

import { atomWithStorage } from 'jotai/utils'

/**
 * 動態選重結果介面（單個字頻源）
 */
export interface 動態選重結果介面 {
  全碼: number
  簡碼: number
}

/**
 * 靜態重碼結果（單個字符集）
 */
export interface 靜態重碼結果介面 {
  重碼組數: number
  重碼字數: number
  總字符數: number
  重碼率: number
}

/**
 * 全簡碼靜態重碼結果介面（包含全碼和簡碼兩個結果）
 */
export interface 全簡碼靜態重碼結果介面 {
  全碼: 靜態重碼結果介面
  簡碼: 靜態重碼結果介面
}

/**
 * 動態選重分析結果介面
 * 只包含動態選重相關數據
 */
export interface 動態選重分析結果介面 {
  // 動態選重率（按字頻重排）
  知乎簡體動態選重率?: 動態選重結果介面
  北語簡體動態選重率?: 動態選重結果介面
  臺標繁體動態選重率?: 動態選重結果介面
  古籍繁體動態選重率?: 動態選重結果介面
  繁簡聯合動態選重率?: 動態選重結果介面

  // 動態選重率（保持原序）
  知乎簡體動態選重率原序?: 動態選重結果介面
  北語簡體動態選重率原序?: 動態選重結果介面
  臺標繁體動態選重率原序?: 動態選重結果介面
  古籍繁體動態選重率原序?: 動態選重結果介面
  繁簡聯合動態選重率原序?: 動態選重結果介面

  // 元數據
  更新時間?: string
}

/**
 * 動態選重分析原子狀態（持久化到 localStorage）
 */
export const 動態選重分析原子狀態 = atomWithStorage<動態選重分析結果介面 | null>(
  '動態選重分析',
  null
)

