/**
 * 簡碼效率分析服務
 *
 * 核心概念：
 * - 字頻加權碼長 = 字頻加權平均碼長
 * - 值越小越好（表示平均每個字需要按的鍵數越少）
 * - N 值表示使用簡碼的字符個數，例如 N=500 表示前 500 個最有效率的字使用簡碼
 * - 通過比較不同 N 值下的效率，可以找到最佳的簡碼字選擇方案
 */
import type { 頻率數據型别 } from '../types'

/**
 * 單個 N 值的簡碼效率結果
 */
interface N值簡碼效率結果介面 {
  最有效率的簡碼個數: number
  字頻加權碼長: number
}

/**
 * 簡碼效率結果介面（優化版）
 *
 * @property 完整字符字符串 - 最大 N 值時的完整字符串，其他 N 值通過截取前 N 個字符獲得
 * @property N值結果 - 所有 N 值的效率數據
 */
export interface 簡碼效率結果介面 {
  完整字符字符串: string
  N值結果: N值簡碼效率結果介面[]
}

/**
 * 計算簡碼效率
 *
 * 這個函數接受已處理好的簡碼和全碼映射，適合在已經完成碼表解析後使用。
 * 相比 calculateShortCodeEfficiency，這個版本不需要處理選重邏輯，因爲輸入的 Map 已經包含了選重信息。
 *
 * @param 字頻數據 - 字符到字頻的映射（歸一化後的頻率，總和爲 1）
 * @param 簡碼映射 - 字符到簡碼的映射（已包含選重鍵）
 * @param 全碼映射 - 字符到全碼的映射（已包含選重鍵）
 * @param 最大碼長 - 方案的最大碼長（例如 4），用於判斷簡碼是否有效
 * @param N值列表 - 要計算的 N 值列表，例如 [0, 5, 10, 25, 50, ..., 2000]
 * @returns 不同 N 值下的簡碼效率結果數組，包含 28 個數據點
 *
 * @example
 * // 計算知乎簡體字頻下的簡碼效率
 * const 結果 = 計算指定字頻下之簡碼效率(
 *   知乎簡體字頻,
 *   簡碼加選重鍵表,
 *   全碼加選重鍵表,
 *   4,
 *   [0, 5, 10, 25, 50, 100, ...]
 * )
 * // 結果[0] = { 最有效率的簡碼個數: 0, 字頻加權碼長: 4.2, 對應字符字符串: '' }  // 全部用全碼
 * // 結果[5] = { 最有效率的簡碼個數: 100, 字頻加權碼長: 3.1, 對應字符字符串: '的一...' }  // 前100個用簡碼
 */
/**
 * 存檔與網頁端共用的 N 值網格
 *
 * 方案 JSON 裏存的就是這一組；對比頁按 N 值反查（0/25/50/100/200/500 那幾欄），
 * 網格對不上那幾欄就只能畫「-」。所以頁面、`pnpm recompute` 必須用同一份。
 * 低位密、2000 封頂，是因爲簡碼效率的差異幾乎都落在前兩千字。
 */
export const 簡碼效率N值列表 = [
  0, 5, 10, 25, 50, 75, 100, 150, 200, 250, 300, 400, 500, 600, 700, 800, 900, 1000, 1100, 1200,
  1300, 1400, 1500, 1600, 1700, 1800, 1900, 2000,
] as const

interface 簡碼字符整理項 {
  字符: string
  簡碼長度: number
  全碼長度: number
  碼長差值: number
  字頻: number
  字頻碼長乘積: number
}

/**
 * 一次遍歷同時算出：基礎加權碼長、總字頻、按收益排序的有效簡碼項。
 *
 * 基礎加權碼長 = 所有字符都用全碼時的 Σ(字頻 × 碼長)；
 * 切換前 N 個字符到簡碼後，分子只需減去這 N 個字的 (字頻 × 碼長差)，
 * 而「字頻 × 碼長差」正是排序鍵，所以排序後的前綴和直接給出節省量。
 */
interface 效率彙總 {
  基礎加權碼長: number
  總字頻: number
  排序項: 簡碼字符整理項[]
}

function 彙總簡碼效率(
  字頻數據: 頻率數據型别,
  簡碼映射: Map<string, string>,
  全碼映射: Map<string, string>,
  最大碼長: number
): 效率彙總 {
  let 基礎加權碼長 = 0
  let 總字頻 = 0
  const 排序項: 簡碼字符整理項[] = []

  for (const [字符, 字頻] of Object.entries(字頻數據)) {
    if (字頻 <= 0) continue
    const 簡碼 = 簡碼映射.get(字符)
    const 全碼 = 全碼映射.get(字符)
    if (!簡碼 || !全碼) continue

    const 簡碼長度 = 簡碼.length
    const 全碼長度 = 全碼.length
    基礎加權碼長 += 字頻 * 全碼長度
    總字頻 += 字頻

    if (簡碼長度 < 全碼長度 && 簡碼長度 < 最大碼長) {
      排序項.push({
        字符,
        簡碼長度,
        全碼長度,
        碼長差值: 全碼長度 - 簡碼長度,
        字頻,
        字頻碼長乘積: 字頻 * (全碼長度 - 簡碼長度),
      })
    }
  }

  排序項.sort((a, b) => b.字頻碼長乘積 - a.字頻碼長乘積)
  return { 基礎加權碼長, 總字頻, 排序項 }
}

/**
 * 整理並按收益排序有效簡碼
 *
 * 有效簡碼：簡碼比全碼短，且短於方案最大碼長。
 * 排序鍵是字頻 ×（全碼長 − 簡碼長），大者在前。
 */
function 整理有效簡碼字符(
  字頻數據: 頻率數據型别,
  簡碼映射: Map<string, string>,
  全碼映射: Map<string, string>,
  最大碼長: number
): { 處理後字符: 簡碼字符整理項[]; 按乘積排序: 簡碼字符整理項[] } {
  const 處理後字符: 簡碼字符整理項[] = []

  for (const [字符, 字頻] of Object.entries(字頻數據)) {
    if (字頻 <= 0) continue

    const 簡碼 = 簡碼映射.get(字符)
    const 全碼 = 全碼映射.get(字符)
    if (!簡碼 || !全碼) continue

    const 簡碼長度 = 簡碼.length
    const 全碼長度 = 全碼.length
    const 碼長差值 = 全碼長度 - 簡碼長度

    處理後字符.push({
      字符,
      簡碼長度,
      全碼長度,
      碼長差值,
      字頻,
      字頻碼長乘積: 字頻 * 碼長差值,
    })
  }

  const 有效簡碼字符 = 處理後字符.filter(c => c.簡碼長度 < c.全碼長度 && c.簡碼長度 < 最大碼長)
  const 按乘積排序 = [...有效簡碼字符].sort((a, b) => b.字頻碼長乘積 - a.字頻碼長乘積)
  return { 處理後字符, 按乘積排序 }
}

/**
 * 某個字頻下的有效簡碼，按收益從高到低
 *
 * 前 N 個字符就是該字頻的 top N 簡碼。個數不足 N 時，調用方自行截斷。
 */
export function 取按收益排序的簡碼字符(
  字頻數據: 頻率數據型别,
  簡碼映射: Map<string, string>,
  全碼映射: Map<string, string>,
  最大碼長: number
): string[] {
  return 整理有效簡碼字符(字頻數據, 簡碼映射, 全碼映射, 最大碼長).按乘積排序.map(項 => 項.字符)
}

export function 計算指定字頻下之簡碼效率(
  字頻數據: 頻率數據型别,
  簡碼映射: Map<string, string>,
  全碼映射: Map<string, string>,
  最大碼長: number,
  N值列表: number[]
): 簡碼效率結果介面 {
  const { 基礎加權碼長, 總字頻, 排序項 } = 彙總簡碼效率(字頻數據, 簡碼映射, 全碼映射, 最大碼長)

  // 排序鍵「字頻 × 碼長差」恰好就是切換到簡碼能省下的加權碼長，
  // 所以前綴和 [k] = 前 k 個字的總節省量；每個 N 從 O(全表) 降爲 O(1)。
  const 前綴節省 = new Float64Array(排序項.length + 1)
  for (let i = 0; i < 排序項.length; i++) {
    前綴節省[i + 1] = 前綴節省[i]! + 排序項[i]!.字頻碼長乘積
  }

  const 最大N = Math.max(...N值列表)
  const 實際最大選中數量 = Math.min(最大N, 排序項.length)
  const 完整字符字符串 = 排序項
    .slice(0, 實際最大選中數量)
    .map(c => c.字符)
    .join('')

  const N值結果: N值簡碼效率結果介面[] = N值列表.map(N => {
    const 實際選中數量 = Math.min(N, 排序項.length)
    const 字頻加權碼長 = 總字頻 > 0 ? (基礎加權碼長 - 前綴節省[實際選中數量]!) / 總字頻 : 0
    return { 最有效率的簡碼個數: N, 字頻加權碼長 }
  })

  return {
    完整字符字符串,
    N值結果,
  }
}
